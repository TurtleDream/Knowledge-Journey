/**
 * Промпты для RAG-ответов.
 */

export const RAG_SYSTEM_PROMPT = `Ты — помощник по промпт-инжинирингу. Отвечай ТОЛЬКО на основе контекста, приведённого ниже. Ссылайся на чанки контекста в формате [N], где N — номер чанка. Если контекста мало или в нём нет ответа — добавь в начало ответа пометку [ОБЩИЕ ЗНАНИЯ] и ответь из своих знаний.`;

export function buildRagPrompt(question: string, chunks: string[]): string {
  const ctx = chunks.map((c, i) => `[${i + 1}] ${c}`).join('\n\n');
  return `Контекст:

${ctx}

Вопрос: ${question}

Ответь по правилам из инструкции. Помни: если использовал общие знания, а не контекст — начни ответ с [ОБЩИЕ ЗНАНИЯ].`;
}
